// ── RF-1 静默终态兜底 ─────────────────────────────────────────────

/** 兜底 result 的 finalText 截断长度（与 message_end 捕获的 lastAssistantText 同量级）。 */
export const FALLBACK_FINAL_TEXT_MAX = 2000;

/** 兜底写入器的 IO 注入点（测试用；缺省走真实 fs）。 */
export interface SettlementFallbackIo {
	/** 写 JSON（原子写；缺省 `writeJsonAtomic`）。 */
	writeJson?: (path: string, value: unknown) => void;
	/** 文件存在性探测（缺省 `existsSync`）。 */
	exists?: (path: string) => boolean;
}

export interface SettlementFallbackInput {
	runsDir: string;
	runId: string;
	/** 本回合最后一条 assistant 文本（此处按 2000 截断）。 */
	lastAssistantText?: string;
	/** 仅供 summary/诊断（不参与判据）。 */
	lastStopReason?: string;
	/** 注入时钟（缺省 new Date()）。 */
	now?: Date;
	/** IO 注入（缺省真实 fs）。 */
	io?: SettlementFallbackIo;
	/** dispatch 记录（缺省由本函数 readTabDispatch 读取；供调用方透传免重读）。 */
	dispatch?: TabDispatchRecord | null;
}

export type SettlementFallbackOutcome =
	/** 已写入兜底 result */
	| "written"
	/** 已有 result.json（真 tab-finish 或上一次兜底）→ 让路，绝不覆盖 */
	| "skip-has-result"
	/** 无 dispatch 记录 ⇒ 非派发会话，不猜 */
	| "skip-no-dispatch"
	/**
	 * 常驻身份豁免：`lms-*`（local master）/ `master-*`（master 派发）明令不调 tab-finish、不退出，
	 * 给它们写兜底只会制造**永久 unconfirmed**（见 writeSettlementFallback 内的注释）。
	 */
	| "skip-persistent-identity"
	/** 写入/校验失败（已 console.error；**不抛**） */
	| "error";

/**
 * RF-1：tab 回合结束但未调用 tab-finish ⇒ 落一条 `status:"unconfirmed"` + `autoGenerated:true` 的结果。
 *
 * 语义（为什么不是 failed/completed）：
 *   - 它不是**工作流终态**：tab 只是本回合 settle 了，仍可能被 steer 继续；
 *   - 它不是**完成**：把「没回报」写成 completed 就是撒谎；
 *   - 它必须**能唤醒主会话**：因此沿用 result.json 通道（event-bus 只 watch `*.result.json`）。
 *
 * 硬约束：
 *   1. `status` 永不 `"completed"`（本函数唯一构造点，字面常量，无参数可覆盖）。
 *   2. **已有 result.json 绝不覆盖**（先 exists 检查；写前再查一次以缩竞态窗口）。
 *      ⇒ 同一 runId 多次调用天然幂等（第二次看到自己写的那份 ⇒ skip-has-result）。
 *   3. **无 dispatch 记录不生成**（防误伤非派发会话 / 手工 PI_TAB_RUN_ID）。
 *   3b. **常驻身份豁免**：`taskId` 前缀为 `lms-`（local master）或 `master-`（master 派发）⇒ 返回
 *      `"skip-persistent-identity"`，**不写盘**。这两类 tab 明令不调 tab-finish、不退出
 *      （`runtime/local-master-launch.ts:249`），给它们写兜底只会造永久 unconfirmed 污染（详 ④）。
 *   4. **never-throw**：任何异常只记 console.error 并返回 "error"。
 *
 * 可测性：`io` 注入是**函数参数**（不把 fs 调用散在事件体里），测试可直接注入会抛的写函数。
 * 事件体（`registerTabTelemetry` 的 agent_settled）是薄壳，与本函数共享同一实现（不双写逻辑）。
 */
export function writeSettlementFallback(input: SettlementFallbackInput): SettlementFallbackOutcome {
	const { runsDir, runId } = input;
	try {
		const exists = input.io?.exists ?? existsSync;
		const writeJson = input.io?.writeJson ?? writeJsonAtomic;
		const path = tabResultPath(runsDir, runId);

		// ② 已有结果 → 让路（幂等 + 绝不覆盖真 tab-finish）
		if (exists(path)) return "skip-has-result";

		// ③ 无派发记录 → 不是派发出的 tab，不猜
		const dispatch = input.dispatch !== undefined ? input.dispatch : readTabDispatch(runsDir, runId);
		if (!dispatch) return "skip-no-dispatch";

		// ④ 常驻身份豁免（2026-10-18，GLM D-3）：
		//    local master（taskId=`lms-<scope>`，见 runtime/local-master-launch.ts:249 明令「不要调 tab-finish、
		//    不要退出」）与 master 派发（`master-*`）都是**常驻** tab：它们每次 settle 都是设计行为，
		//    不是「忘了回报」。给它们写兜底 ⇒ 每回合一条**永久** unconfirmed，而 unconfirmed 的
		//    attention:true（runtime/frontier-carriers.ts:203）会把这个仓的 attention 抬成 >0 ⇒
		//    同仓所有受监管 tab 派生 BLOCKED_USER（规则 5），STALLED 从此不可达。
		//    ⇒ 豁免即跳写（不写盘、不造文件）。**只豁免这两个前缀**，不得扩到其它 taskId。
		//    位置：在「已有 result 检查」之后（幂等语义不变）、「写盘」之前（不浪费 IO）。
		const persistentTaskId = typeof dispatch.taskId === "string" ? dispatch.taskId : "";
		if (persistentTaskId.startsWith("lms-") || persistentTaskId.startsWith("master-")) {
			return "skip-persistent-identity";
		}

		const now = input.now ?? new Date();
		const finalText = (input.lastAssistantText ?? "").slice(0, FALLBACK_FINAL_TEXT_MAX);
		const stop = input.lastStopReason ? ` (lastStopReason=${input.lastStopReason})` : "";
		const summary = `tab 回合结束但未调用 tab-finish${stop}（可能忘记回报）；主会话应主动 reclaim 并核实实际进度`;
		const raw: Record<string, unknown> = {
			id: runId,
			taskId: dispatch.taskId && dispatch.taskId.length > 0 ? dispatch.taskId : "unknown",
			status: "unconfirmed",
			autoGenerated: true,
			finishedAt: now.toISOString(),
			summary,
			finalText: finalText.length > 0 ? finalText : undefined,
			artifacts: [],
			openIssues: ["未调用 tab-finish，成果未经结构化声明"],
		};

		// 写前自校验：兜底本身也必须能过读侧校验（否则文件对全系统不可见 = dead code）
		const check = validateTabResult(raw);
		if (!check.ok || !check.value) {
			console.error(`[tab-runs-runtime] settlement fallback invalid for ${runId}: ${check.errors.join("; ")}`);
			return "error";
		}

		// 写前二次检查：缩小「exists 判定 → 真 tab-finish 落盘」的竞态窗口
		if (exists(path)) return "skip-has-result";
		writeJson(path, check.value);
		return "written";
	} catch (e) {
		// never-throw：兜底失败不得让 tab 崩溃或影响正常退出
		try {
			console.error(`[tab-runs-runtime] settlement fallback failed for ${runId}: ${e instanceof Error ? e.message : String(e)}`);
		} catch { /* console 失败也不能抛 */ }
		return "error";
	}
}

// ── 标签页遥测 + tab-finish ───────────────────────────────────────

/**
 * 注册标签页侧遥测与 tab-finish。仅在当前进程是「已派发的标签页」时生效
 * （PI_TAB_RUN_ID 已设置且非子 agent）。opts 供测试注入。
 */
export function registerTabTelemetry(
	pi: ExtensionAPI,
	opts?: {
		tabRunId?: string;
		runsDir?: string;
		/** RF-1：兜底写入器的注入点（测试用；缺省真实 fs）。 */
		finishFallback?: SettlementFallbackIo & { now?: () => Date };
	},
): void {
	// 不在此同步早退：CLI flag（--tab-run-id）在扩展加载完成后才就绪，
	// 工厂里 getTabRunId() 可能返回 undefined。改为事件回调/工具执行时惰性解析。
	// 非标签页进程里回调会因 resolveRunId() 返回 undefined 而直接跳过。
	// 空串 env（子 agent 进程注入 PI_TAB_RUNS_DIR=""）视为未设置 → 落默认（|| 链，2026-09-18 与
	// timers-runtime.targetRunTerminal 同型空串坑一并修；?? 链会把空串当有效目录）
	const runsDir = opts?.runsDir || process.env.PI_TAB_RUNS_DIR || defaultTabRunsDir();
	const resolveRunId = (): string | undefined => {
		if (opts?.tabRunId) return opts.tabRunId;
		const id = getTabRunId();
		if (id && !isSubagent()) return id; // 子 agent 不拥有 tab 身份
		return undefined;
	};

	let finished = false; // tab-finish 已给出显式终态
	let lastAssistantText = "";
	let lastStopReason: string | undefined;
	const usageAccum = emptyTabUsage();
	const usageSeen = new Set<string>();

	const writeState = (phase: TabState["phase"], turn: TabState["turn"], extra: Partial<TabState> = {}): void => {
		if (finished) return; // 已终态不再覆盖
		const runId = resolveRunId();
		if (!runId) return; // 非标签页进程：身份未就绪/无身份，跳过
		writeTabState(runsDir, runId, {
			id: runId,
			phase,
			turn,
			terminal: false,
			lastActivityAt: new Date().toISOString(),
			lastAssistantText: lastAssistantText || undefined,
			lastStopReason,
			usage: { ...usageAccum },
			...extra,
		});
	};

	pi.on("session_start", (_event, ctx) => {
		const sessionPath = ctx.sessionManager?.getSessionFile?.() ?? undefined;
		writeState("attached", "idle", { sessionPath, pid: process.pid });
	});

	pi.on("agent_start", () => {
		writeState("working", "working");
	});

	pi.on("tool_execution_start", () => {
		// P1：记下工具起始时刻，供「HANG 60min（working ∧ stop=toolUse）」判据算已跑多久。
		// 注意：并行工具时只保留最后一个起始时刻（spec §3 的字面实现，未做嵌套计数）。
		writeState("working", "working", { currentToolStartedAt: new Date().toISOString() });
	});

	// P1 新增：工具结束时清 currentToolStartedAt（lastActivityAt 由 writeState 自动刷新）。
	// 没有这个事件时，一个已结束的工具会留下真相不明的「起始时刻」
	// ⇒ working ∧ toolUse 会永久表现为「在跑工具已 N 小时」（HANG 误判）。
	pi.on("tool_execution_end", () => {
		writeState("working", "working", { currentToolStartedAt: undefined });
	});

	pi.on("message_end", (event) => {
		const message = event.message;
		if (!message || message.role !== "assistant") return;
		lastStopReason = message.stopReason;
		const text = messageText(message);
		if (text) lastAssistantText = text.slice(0, 2000);
		const usage = message.usage;
		if (usage) {
			// P1-5：复合去重 key，避免缺 id+timestamp 时塌缩成 "undefined" 导致 usage 漏加
			const mid = typeof message.id === "string" ? message.id : "";
			const mts = typeof message.timestamp === "string" ? message.timestamp : "";
			const mrid = typeof message.responseId === "string" ? message.responseId : "";
			const key = `${mid}|${mts}|${mrid}`;
			if (key === "||" || usageSeen.has(key)) {
				// 无法去重的消息（无任何标识）或重复消息：不累加
			} else {
				usageSeen.add(key);
				const n = (v: unknown): number => (typeof v === "number" && Number.isFinite(v) ? v : 0);
				usageAccum.input += n(usage.input);
				usageAccum.output += n(usage.output);
				usageAccum.cacheRead += n(usage.cacheRead);
				usageAccum.cacheWrite += n(usage.cacheWrite);
				const cost = asUsageCost(usage);
				if (cost !== undefined) usageAccum.cost += cost;
				usageAccum.turns += 1;
			}
		}
	});

	// agent_settled = 权威「等待输入」信号（无重试/压缩/排队后续）
	pi.on("agent_settled", () => {
		writeState("waiting", "idle", { currentToolStartedAt: undefined });
		// RF-1 兜底：回合结束但没调 tab-finish ⇒ 落 unconfirmed 结果，让「沉默」成为可感知终态。
		// 薄壳：全部判据/IO 在 writeSettlementFallback（纯借口，可单测）；这里只取当前快照值。
		// 已在 tab-finish 里 finished=true 的会话不再兜底（真结果优先且已落盘）。
		if (finished) return;
		const runId = resolveRunId();
		if (!runId) return;
		try {
			writeSettlementFallback({
				runsDir,
				runId,
				lastAssistantText,
				lastStopReason,
				now: opts?.finishFallback?.now?.(),
				io: opts?.finishFallback,
			});
		} catch {
			// writeSettlementFallback 自身 never-throw；这是第二道保险（绝不影响 tab 退出）
		}
	});

	pi.on("session_shutdown", () => {
		const runId = resolveRunId();
		if (!runId) return;
		if (!finished) {
			writeTabState(runsDir, runId, {
				id: runId,
				phase: "orphaned",
				turn: "unknown",
				terminal: false,
				lastActivityAt: new Date().toISOString(),
				// 会话结束：没有工具在跑了（不留幻影起始时刻）
				currentToolStartedAt: undefined,
				lastAssistantText: lastAssistantText || undefined,
				lastStopReason,
				usage: { ...usageAccum },
				error: "session shutdown without explicit tab-finish",
			});
		}
	});

	// ── tab-finish：唯一显式终态工具（仅标签页内生效）──
	pi.registerTool({
		name: "tab-finish",
		label: "Tab Finish",
		description: [
			"（标签页内部工具）声明本标签页工作流终态：把结构化结果原子写入 tab-runs/<runId>.result.json。",
			"参数：status（completed|failed|cancelled）、summary、可选 finalText/artifacts[]/reportPath/openIssues[]/usage。",
			"runId 取自进程环境（PI_TAB_RUN_ID），不接受外部传入——防止伪造其他 runId。",
			"【完成回报 · 强制】你是主会话派发的任务 tab：全部工作完成后**必须**调用本工具向主会话回报（status=completed + summary + 交付物）——只有 result.json 才会触发 event-bus 唤醒主会话去 reclaim 并编排下一批；不调本工具 = 未完成，主会话会一直等你。",
			"只有调用了本工具（或明确失败事件）才代表工作流完成；普通回合 stop 不算完成。",
			"重复调用拒绝（结果只写一次）。",
			// §23：trace worker 的 Trace-specific 完成契约（按 session profile 注入）
			...(isTraceWorker() ? [
				"【TRACE 完成契约】你若正在运行此工具，说明你是 trace worker tab：调用前必须已写好 trajectory.md 与 validation.json 到任务指定的 lanes/<lane>/ 目录；",
				"status=completed 表示你已尽力完成独立求解并留下全部证据；status=failed 也必须调用（带已有证据与 openIssues）——静默挂起会让整个 run 降级。",
			] : []),
		].join(" "),
		parameters: Type.Object({
			status: Type.String({ description: "completed | failed | cancelled" }),
			summary: Type.String({ description: "结果摘要（给主会话的交接材料）" }),
			finalText: Type.Optional(Type.String({ description: "最终文本（截断 4000 字符）" })),
			artifacts: Type.Optional(Type.Array(Type.String(), { description: "交付物路径列表" })),
			reportPath: Type.Optional(Type.String({ description: "报告文件路径（如 plans/…）" })),
			openIssues: Type.Optional(Type.Array(Type.String(), { description: "未决问题列表" })),
		}),
		renderCall(args, theme) {
			const color = args.status === "completed"
				? theme.fg("success", args.status)
				: args.status === "failed"
					? theme.fg("error", args.status)
					: theme.fg("warning", args.status);
			return new Text(`${theme.fg("toolTitle", theme.bold("tab-finish"))} ${color} ${theme.fg("dim", String(args.summary ?? "").slice(0, 40))}`, 0, 0);
		},
		renderResult(result, _options, theme) {
			const text = result.content[0]?.type === "text" ? result.content[0].text : "";
			return new Text(result.isError ? theme.fg("error", text) : theme.fg("success", text), 0, 0);
		},
		async execute(_toolCallId, rawParams) {
			if (finished) {
				return { content: [{ type: "text", text: "tab-finish 已调用过，结果只写一次" }], isError: true };
			}
			const runId = resolveRunId();
			if (!runId) {
				return { content: [{ type: "text", text: "当前进程不是标签页（无 tab-run-id）" }], isError: true };
			}
			const p = rawParams as Record<string, unknown>;
			const status = String(p.status ?? "");
			const summary = typeof p.summary === "string" ? p.summary.trim() : "";
			if (!["completed", "failed", "cancelled"].includes(status)) {
				return { content: [{ type: "text", text: `status 必须为 completed|failed|cancelled，得到 ${status}` }], isError: true };
			}
			if (!summary) {
				return { content: [{ type: "text", text: "summary 必填" }], isError: true };
			}
			const dispatch = readTabDispatch(runsDir, runId);
			const raw: Record<string, unknown> = {
				id: runId,
				taskId: dispatch?.taskId ?? "",
				status,
				finishedAt: new Date().toISOString(),
				summary,
				finalText: typeof p.finalText === "string" ? p.finalText.slice(0, 4000) : undefined,
				artifacts: Array.isArray(p.artifacts) ? p.artifacts.filter((a): a is string => typeof a === "string").slice(0, 50) : undefined,
				reportPath: typeof p.reportPath === "string" ? p.reportPath : undefined,
				openIssues: Array.isArray(p.openIssues) ? p.openIssues.filter((a): a is string => typeof a === "string").slice(0, 50) : undefined,
				usage: usageAccum.turns > 0 ? { ...usageAccum } : undefined,
			};
			const check = validateTabResult(raw);
			if (!check.ok || !check.value) {
				return { content: [{ type: "text", text: `结果校验失败: ${check.errors.join("; ")}` }], isError: true };
			}
			writeJsonAtomic(tabResultPath(runsDir, runId), check.value);
			finished = true;
			// tab 侧也回报：本窗口用户可见（主会话侧由 event-bus 的 fs.watch 感知后再回报）
			try {
				sendWindowsToast({
					title: `${status === "completed" ? "✅" : "❌"} tab ${runId} ${status}`,
					body: `${check.value.summary.slice(0, 100)}${check.value.artifacts?.length ? ` (${check.value.artifacts.length} artifacts)` : ""}`,
					duration: "long",
				});
			} catch { /* toast 失败不阻塞 */ }
			// 同步写终态 state（result 优先，state 仅作冗余）
			writeTabState(runsDir, runId, {
				id: runId,
				phase: status === "completed" ? "completed" : status === "failed" ? "failed" : "cancelled",
				turn: "idle",
				terminal: true,
				lastActivityAt: new Date().toISOString(),
				lastAssistantText: check.value.finalText ?? check.value.summary,
				usage: check.value.usage ? { ...check.value.usage } : undefined,
			});
			return { content: [{ type: "text", text: `✓ tab-finish ${status}: result written for ${runId}` }] };
		},
	});

	// ── tab-report：tab 主动向主会话回报消息（反向注入通道）──
	pi.registerTool({
		name: "tab-report",
		label: "Tab Report",
		description: [
			"（标签页内部工具）主动向主会话回报消息：写入 ~/.pi/agent/reports/，主会话感知后注入用户消息被模型处理。",
			"用于工作完成、需要主会话决策/关注、或重要进展时主动联系主会话（不必等主会话轮询）。",
			"参数：message（回报内容）、可选 taskId / summary。from 取自本标签页 runId。",
		].join(" "),
		parameters: Type.Object({
			message: Type.String({ description: "回报消息（注入主会话的内容，≤1000 字符）" }),
			taskId: Type.Optional(Type.String({ description: "关联任务号" })),
			summary: Type.Optional(Type.String({ description: "简短摘要（≤200 字符）" })),
		}),
		renderCall(args, theme) {
			return new Text(`${theme.fg("toolTitle", theme.bold("tab-report"))} ${theme.fg("accent", `→main`)} ${theme.fg("dim", String(args.message ?? "").slice(0, 40))}`, 0, 0);
		},
		renderResult(result, _options, theme) {
			const text = result.content[0]?.type === "text" ? result.content[0].text : "";
			return new Text(result.isError ? theme.fg("error", text) : theme.fg("success", text), 0, 0);
		},
		async execute(_toolCallId, rawParams) {
			const runId = resolveRunId();
			if (!runId) {
				return { content: [{ type: "text", text: "当前进程不是标签页（无 tab-run-id）" }], isError: true };
			}
			const p = rawParams as { message?: string; taskId?: string; summary?: string };
			const raw = (p.message ?? "").trim();
			if (!raw) {
				return { content: [{ type: "text", text: "message 必填" }], isError: true };
			}
			// ── 显式截断（2026-10-16 修复：“**静默截断 = 静默丢失**”）──────────────
			// 旧行为：`message.slice(0, 1000)` 无任何标记、仍报 `✓ 已回报` ⇒ 主会话看到的正文被截断
			// 而两头都不知（实测：4 份回报长度**恰好全为 1000**，其中一整个「离线项 4 条」段被丢）。
			// 新行为：① 全文落盘（不丢内容）；② 正文尾部**显式**追加 TRUNCATED 标记 + 全文路径；
			//          ③ 工具返回**警告**（告知发送方已截断，请改走「长内容落盘 + 给路径」）。
			const MAX_MESSAGE_CHARS = 1000;
			let message = raw;
			let fullTextPath: string | undefined;
			let omitted = 0;
			if (raw.length > MAX_MESSAGE_CHARS) {
				const dir = defaultReportsDir();
				try {
					if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
					fullTextPath = join(dir, `${runId}-${Date.now().toString(36)}.full.txt`);
					writeFileSync(fullTextPath, raw, "utf8");
				} catch {
					fullTextPath = undefined; // 落盘失败不阻断回报（标记仍写，并降级为“未落盘”）
				}
				// 先算标记长度再切片：保证**标记本身**不被下游截断（否则又成静默丢失）
				const markerOf = (n: number): string =>
					`\n[TRUNCATED: ${n} chars omitted — 内容在 ${fullTextPath ?? "(落盘失败，原文未保留)"}]`;
				let keep = MAX_MESSAGE_CHARS - markerOf(raw.length - MAX_MESSAGE_CHARS).length;
				if (keep < 0) keep = 0;
				omitted = raw.length - keep;
				message = raw.slice(0, keep) + markerOf(omitted);
			}
			try {
				sendReportToMain({
					from: runId,
					message,
					taskId: p.taskId,
					summary: p.summary?.slice(0, 200),
				});
				if (omitted > 0) {
					return {
						content: [{
							type: "text",
							text: `⚠ 已向主会话回报，但**正文被截断**（省略 ${omitted} 字符；已显式标注）。全文已落盘: ${fullTextPath ?? "(落盘失败)"}\n后续请把长内容写文件、在 message 里给路径（截断即丢失）。`,
						}],
					};
				}
				return { content: [{ type: "text", text: `✓ 已向主会话回报（runId=${runId}）` }] };
			} catch (err) {
				return { content: [{ type: "text", text: `回报失败: ${err instanceof Error ? err.message : String(err)}` }], isError: true };
			}
		},
	});
}

function asUsageCost(usage: Record<string, unknown>): number | undefined {
	const cost = usage.cost;
	if (typeof cost === "number" && Number.isFinite(cost)) return cost;
	if (cost && typeof cost === "object" && typeof (cost as { total?: unknown }).total === "number") {
		return (cost as { total: number }).total;
	}
	return undefined;
}

// ── 主会话侧：tab-status / reclaim-tabs / /tabs ──────────────────

const TERMINAL_PHASES = new Set(["completed", "failed", "cancelled"]);

function viewToBrief(view: TabStatusView): Record<string, unknown> {
	return {
		runId: view.runId,
		taskId: view.dispatch?.taskId,
		title: view.dispatch?.title,
		phase: view.phase,
		turn: view.turn,
		terminal: view.terminal,
		resultMissing: view.resultMissing,
		dispatchStatus: view.dispatch?.dispatchStatus,
		source: view.source,
		lastStopReason: view.state?.lastStopReason,
		lastAssistantText: view.lastAssistantText?.slice(0, 300),
		usage: view.usage,
		sessionPath: view.state?.sessionPath,
		lastActivityAt: view.state?.lastActivityAt ?? view.dispatch?.dispatchedAt,
		result: view.result ? {
			status: view.result.status,
			summary: view.result.summary?.slice(0, 500),
			reportPath: view.result.reportPath,
			artifacts: view.result.artifacts,
			openIssues: view.result.openIssues,
		} : undefined,
	};
}

export { viewToBrief };

/**
 * 回收分桶（P0 展示口径 → 主会话编排动作）。
 *
 * 2026-10-18（GLM D-2）：`unconfirmed` **不再归 failed**。
 *   - failed 的语义是「已失败 ⇒ 可以另起新 tab」；而 unconfirmed 只意味着「这回合 settle 了、成果未声明」——
 *     tab 可能只是中途停下、成果真实存在（SBS-B1 的 commit 是真的）。归 failed 会诱导主会话
 *     「失败 → 另派」，即与可能复活的原 tab 产生**双写竞争**（两个 tab 改同一批文件）。
 *   - 因此拆出独立一类 `"unconfirmed"`，语义 =「需人工核实实际进度，核实前不得直接另派同一任务」
 *     （用户可见文案必须避用「重派 / re-run / 重启 / retry」字样，见 reclaim-tabs 分组文案）。
 *   - 顺序：unconfirmed 先于 TERMINAL_PHASES（后者只含 completed/failed/cancelled，理论上不重叠，
 *     显式前置是为了让「phase 字面 unconfirmed ⇒ 独立桶」不依赖 phase 集合的当前内容）。
 */
function classifyForReclaim(
	view: TabStatusView,
): "ready" | "pending" | "awaitingInput" | "unconfirmed" | "failed" | "orphaned" {
	if (view.dispatch?.dispatchStatus === "launch_failed") return "failed";
	if (view.phase === "unconfirmed") return "unconfirmed";
	if (TERMINAL_PHASES.has(view.phase)) return view.resultMissing ? "pending" : "ready";
	if (view.phase === "awaitingInput" || view.phase === "waiting") return "awaitingInput";
	if (view.phase === "orphaned") return "orphaned";
	return "pending";
}

export { classifyForReclaim };

/**
 * 注册主会话侧回收工具：tab-status、reclaim-tabs、/tabs 命令。
 * 在所有进程注册（标签页内查自己、主会话查全部），子 agent 禁用。
 */
export function registerTabStatusTools(
	pi: ExtensionAPI,
	opts?: { runsDir?: string; sessionsRoot?: string },
): void {
	const runsDir = opts?.runsDir ?? defaultTabRunsDir();
	const sessionsRoot = opts?.sessionsRoot ?? defaultSessionsRoot();
	const isSubagentProcess = isSubagent();
	const ownTabRunId = getTabRunId();

	const scopedRunIds = (): string[] => {
		if (ownTabRunId) return [ownTabRunId];
		return listTabDispatches(runsDir).map((d) => d.id);
	};

	// ── tab-status ──
	pi.registerTool({
		name: "tab-status",
		label: "Tab Status",
		description: [
			"查询标签页回收状态：tab-status({ runId?, taskId?, includeText? })。",
			"返回结构化 records[]：runId/taskId/phase/turn/terminal/resultMissing/source/lastStopReason/usage/result 摘要。",
			"phase：dispatched|attached|working|waiting|completed|failed|cancelled|orphaned|unconfirmed。",
			"判态优先级：显式结果文件 > 标签页遥测 state > 会话 JSONL 保守探活；只有 completed/failed/cancelled 且 result 存在才是终态。",
		].join(" "),
		parameters: Type.Object({
			runId: Type.Optional(Type.String({ description: "指定 runId；缺省列出全部" })),
			taskId: Type.Optional(Type.String({ description: "按 taskId 过滤" })),
			includeText: Type.Optional(Type.Boolean({ description: "返回 lastAssistantText" })),
		}),
		renderCall(args, theme) {
			const target = args.runId ?? args.taskId ?? "(all)";
			return new Text(`${theme.fg("toolTitle", theme.bold("tab-status"))} ${theme.fg("accent", target)}`, 0, 0);
		},
		renderResult(result, { expanded }, theme) {
			const d = result.details as { records?: Array<Record<string, unknown>> } | undefined;
			const records = d?.records ?? [];
			if (!expanded) {
				const line = records.length
					? records.map((r) => `${r.phase}:${r.runId}${r.resultMissing ? "(noResult)" : ""}`).join(", ")
					: "(none)";
				return new Text(theme.fg("dim", `tab-status ${records.length}: ${line.slice(0, 150)}`), 0, 0);
			}
			const c = new Container();
			c.addChild(new Text(theme.fg("toolTitle", `tab-status (${records.length})`), 0, 0));
			for (const r of records) {
				c.addChild(new Spacer(1));
				c.addChild(new Text(`${r.phase} ${r.runId}${r.taskId ? ` task=${r.taskId}` : ""}${r.terminal ? " ✓terminal" : ""}${r.resultMissing ? " ⚠noResult" : ""}`, 0, 0));
				c.addChild(new Text(theme.fg("dim", `  src=${r.source} stop=${r.lastStopReason ?? "-"} ${String(r.lastAssistantText ?? "").slice(0, 80)}`), 0, 0));
				if (r.result && typeof r.result === "object") {
					c.addChild(new Text(theme.fg("dim", `  result=${(r.result as { status?: string }).status}: ${String((r.result as { summary?: string }).summary ?? "").slice(0, 80)}`), 0, 0));
				}
			}
			return c;
		},
		async execute(_toolCallId, rawParams) {
			if (isSubagentProcess) return { content: [{ type: "text", text: "子 agent 中不可查询标签页回收" }], isError: true };
			const p = rawParams as { runId?: string; taskId?: string; includeText?: boolean };
			let ids = scopedRunIds();
			if (p.runId) ids = ids.filter((id) => id === p.runId);
			if (ids.length === 0 && p.runId) {
				// 指定 runId 但账本里没有 → 仍尝试直接组装（可能账本被清）
				ids = [p.runId];
			}
			if (p.taskId) {
				const dispatches = new Map(listTabDispatches(runsDir).map((d) => [d.id, d]));
				ids = ids.filter((id) => dispatches.get(id)?.taskId === p.taskId);
			}
			const records = ids.map((id) => viewToBrief(buildTabStatusView(runsDir, id, sessionsRoot)));
			if (records.length === 0) {
				return { content: [{ type: "text", text: "No tabs" }], details: { records: [] } };
			}
			const lines = records.map((r) => {
				const resultMissing = r.resultMissing ? " (resultMissing)" : "";
				const resultTag = r.result ? ` → ${(r.result as { status?: string }).status}` : "";
				return `${String(r.phase).padEnd(12)} ${r.runId}${r.taskId ? ` task=${r.taskId}` : ""}${resultMissing}${resultTag}`;
			});
			return { content: [{ type: "text", text: lines.join("\n") }], details: { records } };
		},
	});

	// ── reclaim-tabs ──
	pi.registerTool({
		name: "reclaim-tabs",
		label: "Reclaim Tabs",
		description: [
			"回收标签页结果：reclaim-tabs({ runIds, includeText? })。",
			"永不阻塞、立即返回当前快照（2026-08-13 起移除轮询硬等；wait/timeoutMs/intervalMs 为废弃参数，仅向后兼容，调用方不应依赖）。",
			"完成感知交给 event-bus（子 tab 写 result.json 自动唤醒主会话），编排巡检用 set-timer。",
			"禁轮询: 不要用 turn 反复重调本工具/tab-status 等待状态变化；等待靠完成事件 + 一次性 set-timer 兜底。",
			"返回 ready[]（终态可取结果）/ pending[]（进行中）/ awaitingInput[]（等待输入，非完成）/ unconfirmed[]（回合结束但未回报：**需人工核实实际进度，核实前不得直接另派同一任务**）/ failed[]（真失败/派发失败）/ orphaned[]。",
			"result 缺失的终态标 resultMissing=true + completion=unconfirmed，绝不静默当成功。",
		].join(" "),
		parameters: Type.Object({
			runIds: Type.Array(Type.String(), { description: "要回收的 runId 列表（launch-tabs 返回）" }),
			wait: Type.Optional(Type.Boolean({ description: "（废弃）忽略：本工具永不阻塞等待" })),
			timeoutMs: Type.Optional(Type.Number({ description: "（废弃）忽略" })),
			intervalMs: Type.Optional(Type.Number({ description: "（废弃）忽略" })),
			includeText: Type.Optional(Type.Boolean({ description: "返回 lastAssistantText" })),
		}),
		renderCall(args, theme) {
			return new Text(`${theme.fg("toolTitle", theme.bold("reclaim-tabs"))} ${theme.fg("accent", `${args.runIds.length} tabs`)}`, 0, 0);
		},
		renderResult(result, { expanded }, theme) {
			const d = result.details as { ready?: unknown[]; pending?: unknown[]; awaitingInput?: unknown[]; unconfirmed?: unknown[]; failed?: unknown[]; orphaned?: unknown[] } | undefined;
			if (!d) return new Text("", 0, 0);
			const summary = `ready=${d.ready?.length ?? 0} pending=${d.pending?.length ?? 0} awaitingInput=${d.awaitingInput?.length ?? 0} unconfirmed=${d.unconfirmed?.length ?? 0} failed=${d.failed?.length ?? 0} orphaned=${d.orphaned?.length ?? 0}`;
			if (!expanded) return new Text(theme.fg("success", `reclaim-tabs: ${summary}`), 0, 0);
			const c = new Container();
			c.addChild(new Text(theme.fg("toolTitle", `reclaim-tabs: ${summary}`), 0, 0));
			for (const [label, group] of [["ready", d.ready], ["pending", d.pending], ["awaitingInput", d.awaitingInput], ["unconfirmed", d.unconfirmed], ["failed", d.failed], ["orphaned", d.orphaned]] as const) {
				if (!group || group.length === 0) continue;
				c.addChild(new Spacer(1));
				c.addChild(new Text(theme.fg("accent", label), 0, 0));
				for (const item of group as Array<Record<string, unknown>>) {
					c.addChild(new Text(theme.fg("dim", `  ${item.runId}${item.result ? ` → ${(item.result as { status?: string }).status}` : ""} ${String(item.lastAssistantText ?? "").slice(0, 60)}`), 0, 0));
				}
			}
			return c;
		},
		async execute(_toolCallId, rawParams) {
			if (isSubagentProcess) return { content: [{ type: "text", text: "子 agent 中不可回收标签页" }], isError: true };
			const p = rawParams as { runIds?: string[]; includeText?: boolean };
			const runIds = (p.runIds ?? []).filter((id) => typeof id === "string" && id);
			if (runIds.length === 0) return { content: [{ type: "text", text: "runIds 必填" }], isError: true };

			// 永不阻塞：单次快照立即返回；完成感知交给 event-bus / set-timer 巡检
			const views = new Map<string, TabStatusView>();
			for (const id of runIds) views.set(id, buildTabStatusView(runsDir, id, sessionsRoot));

			const groups = { ready: [] as Record<string, unknown>[], pending: [] as Record<string, unknown>[], awaitingInput: [] as Record<string, unknown>[], unconfirmed: [] as Record<string, unknown>[], failed: [] as Record<string, unknown>[], orphaned: [] as Record<string, unknown>[] };
			for (const view of views.values()) {
				const kind = classifyForReclaim(view);
				const brief = viewToBrief(view);
				if (TERMINAL_PHASES.has(view.phase) && !view.resultMissing) brief.completion = "confirmed";
				else if (TERMINAL_PHASES.has(view.phase)) brief.completion = "unconfirmed";
				groups[kind].push(brief);
			}
			const summary = `ready=${groups.ready.length} pending=${groups.pending.length} awaitingInput=${groups.awaitingInput.length} unconfirmed=${groups.unconfirmed.length} failed=${groups.failed.length} orphaned=${groups.orphaned.length}`;
			return {
				content: [{
					type: "text",
					text: `reclaim-tabs: ${summary}\n\n` + [
						groups.ready.length ? `ready:\n${groups.ready.map((r) => `  ✓ ${r.runId}${r.result ? ` → ${(r.result as { status?: string }).status}: ${String((r.result as { summary?: string }).summary ?? "").slice(0, 120)}` : ""}`).join("\n")}` : "",
						groups.awaitingInput.length ? `awaitingInput:\n${groups.awaitingInput.map((r) => `  ⏳ ${r.runId} (等待输入，不是完成)`).join("\n")}` : "",
						// 文案硬约束（GLM D-2）：只提「核实实际进度」，**全文不得**出现「重派 / re-run / 重启 / retry」字样
						//（否则等于建议另起新 tab ⇒ 与可能复活的原 tab 双写竞争）。故用「另派同一任务」。
						groups.unconfirmed.length ? `unconfirmed:\n${groups.unconfirmed.map((r) => `  ❓ ${r.runId} (回合结束但未调用 tab-finish；需人工核实实际进度，核实前不得直接另派同一任务；先读该 tab 的交付物/计划文件再决定)`).join("\n")}` : "",
						groups.failed.length ? `failed:\n${groups.failed.map((r) => `  ✗ ${r.runId}${r.result ? ` → ${(r.result as { status?: string }).status}` : " (launch_failed)"}`).join("\n")}` : "",
						groups.pending.length ? `pending:\n${groups.pending.map((r) => `  … ${r.runId}`).join("\n")}` : "",
						groups.orphaned.length ? `orphaned:\n${groups.orphaned.map((r) => `  ☠ ${r.runId}`).join("\n")}` : "",
					].filter(Boolean).join("\n"),
				}],
				details: { ...groups },
			};
		},
	});

	// ── /tabs 命令 ──
	pi.registerCommand("tabs", {
		description: "列出标签页回收状态（人类视角）",
		handler: async (_args, ctx) => {
			if (isSubagentProcess) {
				ctx.ui.notify("子 agent 中不可查看标签页", "warning");
				return;
			}
			const ids = scopedRunIds();
			if (ids.length === 0) {
				ctx.ui.notify("No tabs dispatched", "info");
				return;
			}
			const lines = ids.map((id) => {
				const view = buildTabStatusView(runsDir, id, sessionsRoot);
				const resultMissing = view.resultMissing ? " ⚠noResult" : "";
				const resultTag = view.result ? ` → ${view.result.status}` : "";
				return `${view.phase.padEnd(12)} ${id}${view.dispatch?.taskId ? ` task=${view.dispatch.taskId}` : ""}${resultMissing}${resultTag}  ${String(view.lastAssistantText ?? "").slice(0, 40)}`;
			});
			ctx.ui.notify(`Tabs (${ids.length}):\n${lines.join("\n")}`, "info");
		},
	});
}

