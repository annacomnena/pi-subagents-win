/**
 * _test_trace_fusion_lane_queue.ts — laneConcurrency 续发侧（2026-10-30）
 *
 * 锁定 resumeQueuedLane 的纯逻辑：
 *   ① 无队列文件 ⇒ no-queue（存量全并发路径零影响）
 *   ② 队列空 ⇒ empty
 *   ③ 名额已满 ⇒ no-capacity，且**零 spawn**
 *   ④ 有名额 ⇒ 派队首、移出队列、回写 meta.lanes[X].tabRunId、写计时器
 *   ⑤ 队列派完 ⇒ 删除队列文件
 *
 * 用 fake spawner + 临时目录；不碰真实 tab / 真实 config。
 */

import assert from "node:assert/strict";
import { mkdtempSync, rmSync, mkdirSync, writeFileSync, existsSync, readFileSync, readdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { resumeQueuedLane, readLaneQueue, writeLaneQueue, markLaneQueueDrained } from "./trace-fusion/lane-queue.ts";
import { metaPath } from "./trace-fusion/meta-path.ts";
import type { TraceRunMeta } from "./trace-fusion/types.ts";
import type { TabLaunchOptions } from "./tab-launch-core.ts";

type Call = TabLaunchOptions & { __prompt: string };
function makeFakeSpawner() {
	const calls: Call[] = [];
	const spawner = (opts: TabLaunchOptions) => {
		calls.push({ ...opts, __prompt: String(opts.prompt ?? "") });
		return { title: opts.title, prompt: opts.prompt, model: opts.model };
	};
	return { spawner, calls };
}

const root = mkdtempSync(join(tmpdir(), "tf-laneq-"));
// **账本隔离（2026-11-03 污染分母实测驱动，plans/_probe_tabruns_writers.mjs）**：
// 本套件以前每次跑都往生产 tab-runs 账本写 8 条（实测 delta），污染回收面板。
// `defaultTabRunsDir()` 现在调用时读 env `PI_TAB_RUNS_DIR` ⇒ 顶层设 env 即隔离；
// 末尾的「零写生产」断言是兑现面（设了 env 不等于隔离成功）。
const ISOLATED_TAB_RUNS = join(root, "tab-runs-isolated");
const PROD_TAB_RUNS = join(process.env.USERPROFILE?.trim() ?? process.env.HOME!, ".pi", "agent", "tab-runs");
const prodCountBefore = existsSync(PROD_TAB_RUNS) ? readdirSync(PROD_TAB_RUNS).filter((f) => f.endsWith(".json")).length : 0;
process.env.PI_TAB_RUNS_DIR = ISOLATED_TAB_RUNS;

try {
	const mkMeta = (runDir: string, lanes: Record<"A" | "B" | "C", string>): TraceRunMeta => ({
		runId: "run_test",
		shortId: "test",
		status: "running",
		mode: "diagnose",
		task: "任务",
		repoRoot: root,
		createdAt: new Date().toISOString(),
		baseCommit: "deadbeef",
		headBefore: "deadbeef",
		runDir,
		wtDir: "",
		dispatcherSessionId: "sess-dispatcher-0001",
		laneWallClockMin: 45,
		laneDeadlineAt: new Date(Date.now() + 45 * 60_000).toISOString(),
		lanes: {
			A: { lane: "A", worktree: root, tabRunId: lanes.A, provision: { junction: [], copied: [], commandOk: true, degraded: false, issues: [] } },
			B: { lane: "B", worktree: root, tabRunId: lanes.B, provision: { junction: [], copied: [], commandOk: true, degraded: false, issues: [] } },
			C: { lane: "C", worktree: root, tabRunId: lanes.C, provision: { junction: [], copied: [], commandOk: true, degraded: false, issues: [] } },
		},
	});
	const mkRun = (name: string) => { const d = join(root, name); mkdirSync(join(d, "tab-runs"), { recursive: true }); return d; };
	// 夹具形状必须贴近真实运行时（AGENTS.md R-5）：tab-finish 写的是带 status/autoGenerated 的
	// 结构化结果；回合结束未自报时 tab-runs.ts 兜底写 status=unconfirmed + autoGenerated=true。
	// 旧夹具写 "{}"（两者都不是），已按真实形状重写。
	const markSelf = (d: string, id: string) =>
		writeFileSync(join(d, "tab-runs", `${id}.result.json`), JSON.stringify({ id, taskId: "T1", finishedAt: new Date().toISOString(), status: "completed", summary: "done" }));
	const markAuto = (d: string, id: string) =>
		writeFileSync(
			join(d, "tab-runs", `${id}.result.json`),
			JSON.stringify({ id, taskId: "T1", finishedAt: new Date().toISOString(), status: "unconfirmed", autoGenerated: true, summary: "tab 回合结束未自报" }),
		);
	const base = (runDir: string, meta: TraceRunMeta, over: Partial<Parameters<typeof resumeQueuedLane>[0]> = {}) => ({
		meta, tabRunsDir: join(runDir, "tab-runs"), concurrency: 1,
		wtExe: "wt.exe", piCli: "pi.cmd",
		workerModelFor: () => "prov/x",
		rereadMeta: () => meta,
		...over,
	});

	// ① 无队列
	{
		const d = mkRun("q-none");
		const r = resumeQueuedLane(base(d, mkMeta(d, { A: "tab_a", B: "", C: "" }), { spawnTab: makeFakeSpawner().spawner }));
		assert.equal(r.resumed, false);
		assert.equal((r as { reason: string }).reason, "no-queue");
	}

	// ② 队列空
	{
		const d = mkRun("q-empty");
		markLaneQueueDrained(d, 1); // 显式空队列（保留文件），区别于"无队列"
		const r = resumeQueuedLane(base(d, mkMeta(d, { A: "tab_a", B: "", C: "" }), { spawnTab: makeFakeSpawner().spawner }));
		assert.equal(r.resumed, false);
		assert.equal((r as { reason: string }).reason, "empty");
	}

	// ③ 名额满 ⇒ 零 spawn（A 已派且未终态，并发度 1）
	{
		const d = mkRun("q-full");
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, mkMeta(d, { A: "tab_a", B: "", C: "" }), { spawnTab: spawner }));
		assert.equal(r.resumed, false);
		assert.equal((r as { reason: string }).reason, "no-capacity");
		assert.equal(calls.length, 0, "无名额必须零 spawn");
	}

	// ④ 有名额 ⇒ 派队首 + 移出队列 + 回写 meta + 删队列（队列只剩一条）
	{
		const d = mkRun("q-ok");
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		// A 已自报终态（tab-finish 的真实形状）⇒ 名额空出
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		markSelf(d, "tab_a");
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner }));
		assert.equal(r.resumed, true, `应有名额：${JSON.stringify(r)}`);
		if (r.resumed) {
			assert.equal(r.lane, "B", "派队首 B");
			assert.deepEqual(r.remaining, ["C"], "队列剩 C");
			assert.equal(calls.length, 1, "只派一条");
			assert.equal(meta.lanes.B.tabRunId, r.tabRunId, "meta 回写新 tabRunId");
			const q = readLaneQueue(d);
			assert.ok(q, "队列仍在");
			assert.deepEqual(q!.lanes, ["C"], "磁盘队列剩 C");
			assert.ok(existsSync(join(d, "meta.json")), "meta.json 已落盘");
			assert.equal(JSON.parse(readFileSync(join(d, "meta.json"), "utf8")).lanes.B.tabRunId, r.tabRunId);
		}
	}

	// ⑤ 队列最后一条派完 ⇒ 删除队列文件
	{
		const d = mkRun("q-last");
		writeLaneQueue(d, { lanes: ["C"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "tab_b", C: "" });
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		markSelf(d, "tab_a");
		markSelf(d, "tab_b");
		const { spawner } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner }));
		assert.equal(r.resumed, true);
		if (r.resumed) {
			assert.equal(r.lane, "C");
			assert.equal(existsSync(join(d, "lane-queue.json")), false, "队列空了必须删文件");
		}
	}

	// ⑥ 并发度 2：A 在飞 + B 已终态 ⇒ 仍有名额
	{
		const d = mkRun("q-c2");
		writeLaneQueue(d, { lanes: ["C"], concurrency: 2 });
		const meta = mkMeta(d, { A: "tab_a", B: "tab_b", C: "" });
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		markSelf(d, "tab_b");
		const { spawner } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner, concurrency: 2 }));
		assert.equal(r.resumed, true, "并发 2 下 A 在飞但 B 已终态 ⇒ 应派 C");
	}

	// 溯源链接必须在**拿到真实 tabRunId 的那一刻**写（2026-11-02 乱回事故根因）：
	// 旧行为只在派发时一次性写三路，串行模式下 B/C 无 tabRunId ⇒ 空 targetId 死账
	// ⇒ recipientSessionIdFor 查不到归属 ⇒ 完成消息落回「先到先得」并乱投 global master。
	{
		const d = mkRun("linktrace");
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		// 并发 1 要续发 B，必须先让 A 终态（否则无名额 ⇒ no-capacity，续发不会发生）
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		writeFileSync(join(d, "tab-runs", "tab_a.result.json"), JSON.stringify({ id: "tab_a", taskId: "T1", finishedAt: new Date().toISOString(), status: "completed" }));
		const linksPath = join(d, "links.jsonl");
		const { spawner } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner, linksPath }));
		assert.equal(r.resumed, true, "应成功续发 B");
		const lines = readFileSync(linksPath, "utf8").trim().split("\n").map((l) => JSON.parse(l) as Record<string, unknown>);
		const mine = lines.filter((l) => l.kind === "tab");
		assert.equal(mine.length, 1, "续发只写一条链接");
		assert.equal(mine[0].targetId, (r as { tabRunId: string }).tabRunId, "targetId 必须是真实 tabRunId");
		assert.ok(String(mine[0].targetId).startsWith("tab_"), "targetId 不得为空（空 targetId = 死账）");
		assert.equal(mine[0].sessionId, "sess-dispatcher-0001", "归属必须是派发者会话");
		assert.ok(String(mine[0].detail).includes("lane=B"), "detail 要带 lane");
		void meta;
	}

	console.log("trace-fusion lane-queue tests passed");
	// ── 2026-11-03 新语义：兜底 unconfirmed 不得释放并发名额 ──────────────
	// 起因（实测）：用户中止 lane A ⇒ 回合以 aborted 结束 ⇒ tab-runs.ts:349 兜底生成
	// status=unconfirmed/autoGenerated=true 的 result.json ⇒ 旧版立刻算终态 ⇒ B 起飞，
	// 而 A 的 tab 当时还活着（phase=working、pid 在、心跳新鲜）。⇒「中止一条 = 起下一条」。
	{
		// ⑧ unconfirmed + tab 还活着 ⇒ 无名额（零 spawn）
		const d = mkRun("q-unconfirmed-alive");
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		markAuto(d, "tab_a");
		writeFileSync(
			join(d, "tab-runs", "tab_a.state.json"),
			JSON.stringify({ id: "tab_a", phase: "working", terminal: false, pid: 424242, heartbeatAt: new Date().toISOString() }),
		);
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner, isAlive: () => true }));
		assert.equal(r.resumed, false, "兜底 unconfirmed 且 tab 活着 ⇒ 不得续发");
		assert.equal((r as { reason: string }).reason, "no-capacity");
		assert.equal(calls.length, 0, "无名额必须零 spawn");
	}
	{
		// ⑧b 同一形状但**不注入 isAlive**（走默认真实探活）：验续发侧的默认判活真的是探活
		const d = mkRun("q-unconfirmed-alive-real");
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		markAuto(d, "tab_a");
		writeFileSync(
			join(d, "tab-runs", "tab_a.state.json"),
			JSON.stringify({ id: "tab_a", phase: "working", terminal: false, pid: process.pid, heartbeatAt: new Date().toISOString() }),
		);
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner }));
		assert.equal(r.resumed, false, "默认探活下活 tab + 兜底 unconfirmed ⇒ 必须无名额");
		assert.equal(calls.length, 0);
	}
	{
		// ⑨ unconfirmed + 进程已死 ⇒ 兜底释放名额（否则队列永远差一个 = 2026-11-02 修掉的锁死）
		const d = mkRun("q-unconfirmed-dead");
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		markAuto(d, "tab_a");
		writeFileSync(
			join(d, "tab-runs", "tab_a.state.json"),
			JSON.stringify({ id: "tab_a", phase: "working", terminal: false, pid: 424242, heartbeatAt: new Date().toISOString() }),
		);
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner, isAlive: () => false }));
		assert.equal(r.resumed, true, `进程已死必须释放名额（否则锁死）：${JSON.stringify(r)}`);
		assert.equal(calls.length, 1);
	}
	{
		// ⑩ 无 status 的半截 result（{}）⇒ 保守不算终态（不得静默当完成）
		const d = mkRun("q-result-no-status");
		writeLaneQueue(d, { lanes: ["B"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		writeFileSync(join(d, "tab-runs", "tab_a.result.json"), "{}");
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta, { spawnTab: spawner, isAlive: () => true }));
		assert.equal(r.resumed, false, "读不到有效 status ⇒ 不算终态");
		assert.equal(calls.length, 0);
	}
	// ── 2026-11-03 L4 M3：续发 lane 必须用**自己的**起跑期限 ──
	{
		const d = mkRun("q-perlane-deadline");
		writeLaneQueue(d, { lanes: ["B"], concurrency: 1 });
		// run 级期限**已过期**（A 跑满 45 分钟才自报的真实形状）
		const meta = { ...mkMeta(d, { A: "tab_a", B: "", C: "" }), laneDeadlineAt: new Date(Date.now() - 46 * 60_000).toISOString() };
		markSelf(d, "tab_a");
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, meta as TraceRunMeta, { spawnTab: spawner }));
		assert.equal(r.resumed, true, `A 已终态 ⇒ B 应被派发，实得 ${JSON.stringify(r)}`);
		assert.equal(calls.length, 1);
		const written = JSON.parse(readFileSync(metaPath(d), "utf8")) as { lanes: Record<string, { deadlineAt?: string }> };
		const own = written.lanes.B.deadlineAt;
		assert.ok(own, "续发必须把 B 自己的期限写进 lanes.B.deadlineAt（旧版继承 run 级 ⇒ 起跑即过期）");
		assert.ok(Date.parse(own!) > Date.now() + 40 * 60_000, `B 的期限必须从起跑时刻起算 45min，实得 ${own}`);
	}
	// ── 2026-11-03 L4 M4：派发失败必须落终态并出队 ──
	{
		const d = mkRun("q-dispatch-failed");
		writeLaneQueue(d, { lanes: ["B", "C"], concurrency: 1 });
		const meta = mkMeta(d, { A: "tab_a", B: "", C: "" });
		markSelf(d, "tab_a");
		const r = resumeQueuedLane(base(d, meta, { spawnTab: () => ({ ok: false, error: "WT 不可用" } as never) }));
		assert.equal(r.resumed, false);
		const after = JSON.parse(readFileSync(metaPath(d), "utf8")) as { lanes: Record<string, { laneStatus?: string; laneStatusReason?: string }> };
		assert.equal(after.lanes.B.laneStatus, "dispatch-failed", "派发失败必须写进 meta（旧版不留痕）");
		assert.ok(/WT 不可用/.test(after.lanes.B.laneStatusReason ?? ""), "失败原因必须可见（R-2）");
		assert.deepEqual(readLaneQueue(d)?.lanes, ["C"], "失败的队首必须出队，否则 C 被永久阻塞");
	}
	// ── 2026-11-03 L4 M1：在飞数必须用持锁后重读的 meta（不得用调用方旧快照）──
	{
		const d = mkRun("q-stale-meta");
		writeLaneQueue(d, { lanes: ["C"], concurrency: 1 });
		const fresh = mkMeta(d, { A: "tab_a", B: "tab_b", C: "" }); // 盘上事实：B 已派发且在跑
		const stale = mkMeta(d, { A: "tab_a", B: "", C: "" }); // 调用方拿着 B 未派发的旧快照
		markSelf(d, "tab_a");
		mkdirSync(join(d, "tab-runs"), { recursive: true });
		writeFileSync(join(d, "tab-runs", "tab_b.state.json"), JSON.stringify({ id: "tab_b", phase: "working", terminal: false, pid: process.pid, heartbeatAt: new Date().toISOString() }), "utf8");
		const { spawner, calls } = makeFakeSpawner();
		const r = resumeQueuedLane(base(d, stale, { spawnTab: spawner, rereadMeta: () => fresh }));
		assert.equal(r.resumed, false, `盘上 B 在飞 ⇒ 串行不得再派 C，实得 ${JSON.stringify(r)}`);
		assert.equal(calls.length, 0, "用旧快照算在飞数就会突破 laneConcurrency（变异 N2 的缺口）");
	}
	{
		const prodCountAfter = existsSync(PROD_TAB_RUNS) ? readdirSync(PROD_TAB_RUNS).filter((f) => f.endsWith(".json")).length : 0;
		assert.equal(prodCountAfter, prodCountBefore, `测试不得往生产 tab-runs 账本写记录（前 ${prodCountBefore} 后 ${prodCountAfter}）`);
	}
} finally {
	try { rmSync(root, { recursive: true, force: true, maxRetries: 3, retryDelay: 200 }); } catch { /* 尽力 */ }
}
