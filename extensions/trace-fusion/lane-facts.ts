/**
 * trace-fusion/lane-facts.ts — lane 参与事实与降级记录（2026-11-02，状态机修复 ④）
 *
 * ## 起因（两条实测成立的缺陷）
 *
 * 1. supervisor 原来**固定等 A/B/C 三份 `result.json`**：
 *    `done = lanes.filter(tabRunId && exists(result.json))`，被 `skipLanes` 放弃的 lane 与
 *    spawn 失败的 lane 根本没有 `tabRunId` ⇒ `done` 永远 < 3 ⇒ **永不自动收集**；
 *    run 停在 `running` 占住 `active-run-mutex`（preflight）⇒ 一次 wt.exe 启动失败就锁死 trace-fusion。
 *    宣称的「2/3 降级」在代码里**不可达**。
 * 2. lane tab 被杀/进程死掉 ⇒ 没有 `result.json` ⇒ 同样永远差一个。
 *
 * ## 本模块的判据
 *
 * 收集分母 = **预期参与的 lane 集合**：
 *   - `skipped` / `dispatch-failed`（launch 时就写进 meta）⇒ 一等终态，不进分母；
 *   - 派发成功但 tab 侧已终态（`tab-runs/<id>.state.json` 的 `terminal=true`）⇒ 终态无结果；
 *   - 进程死（`pid` 探活 false，或 pid 缺失且心跳超阈）⇒ 死亡，终态无结果；
 *   - 其余 ⇒ 在跑，收集继续等（`progress`）。
 *
 * **心跳阈是 90s**，与 `tab-runs.ts` 的既定判据一致（该文件注释原话：
 * 「判断死亡的正确方式：pid 探活 ∨ heartbeatAt 距今 > 90s（3 个心跳周期）」）。
 * 单看 `lastActivityAt` 会误判：一次长工具调用期间不写 state（实测有正常工作的 tab
 * 因 lastActivityAt 冻结 61min 被误判僵尸并 abort，随后重复派发）。
 * 因此本模块**绝不用 lastActivityAt 判死**。
 *
 * 降级原因写进 `meta.degradedLanes`（**不得静默**，AGENTS.md R-2），
 * 并由 packet 的 Hard Facts 段呈现（`fusion-packet.ts` 消费该字段）。
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { isProcessAlive } from "../runtime/liveness.ts";
import { readTabResultFile, tabStatePath, writeTabState } from "../tab-runs.ts";
import type { LaneId, TraceRunMeta } from "./types.ts";
import { metaPath } from "./meta-path.ts";

/**
 * 派发时预置 `state.json`（2026-11-02 状态机修复的一部分）。
 *
 * 为什么必须：**dispatch 失败发生在 wt.exe 启动之后（异步）** ⇒ tab 侧的 `session_start`
 * 永远不会写 state ⇒ lane 的 `state.json` 全生缺失。本模块对「无 state 且无结果」
 * 只能保守判在跑 ⇒ 收集永远差一个。
 * 派发那一刻就登记 pid（= 派发者进程，tab 进程是 wt 的子进程），于是「派发者已死 + 从未心跳」
 * 可被确定性判成 launch-dead，不再靠猜。
 * 已存在则不动（不得覆盖 tab 侧写的活状态）。
 */
export function seedDispatchState(tabRunsDir: string, tabRunId: string, opts: { title?: string; cwd?: string; now?: () => number } = {}): void {
	try {
		const p = tabStatePath(tabRunsDir, tabRunId);
		if (existsSync(p)) return;
		const at = new Date(opts.now?.() ?? Date.now()).toISOString();
		writeTabState(tabRunsDir, tabRunId, {
			id: tabRunId,
			phase: "attached",
			turn: "unknown",
			terminal: false,
			pid: process.pid,
			lastActivityAt: at,
			heartbeatAt: at,
		} as never);
	} catch { /* 预置失败不阻断派发 */ }
}

export type LaneFactStatus = "done" | "running" | "queued" | "unconfirmed" | "terminal-no-result" | "dead" | "deadline" | "skipped" | "dispatch-failed";

/** 不进收集分母的状态（一等终态）。 */
export const TERMINAL_LANE_STATUSES = new Set(["skipped", "dispatch-failed"]);

/**
 * 「释放并发名额」的状态（2026-11-03 修复）。与「算不算终态」是**两件事**，必须分开定义：
 *
 * 旧判据 = `existsSync(<tabRunId>.result.json)`（`lane-queue.ts` 与 `supervisor.ts` 各写一份）。
 * 实测事故：用户中止 lane A ⇒ 回合以 aborted 结束 ⇒ `tab-runs.ts:349` 兜底生成
 * `status=unconfirmed, autoGenerated=true` 的 result.json ⇒ 旧判据立刻把 A 记成终态 ⇒
 * 名额释放 ⇒ B 起飞；而 A 的 tab **当时还活着**（state.json phase=working、pid 在、心跳新鲜，
 * 实测 9 个 turn）。后果：`laneConcurrency=1` 的串行约束在账本上满足、在实况上被突破
 * （两条 lane 共用同一 KV 池），且「中止一条 = 起了下一条」。
 *
 * 新判据 = **lane 自报终态**（`tab-finish` 写的 completed/failed/cancelled，`autoGenerated!==true`），
 * 外加「进程已死」这条兜底（判死只用 pid 探活 ∨ 心跳超阈，绝不看 lastActivityAt，见本文件头）：
 * 死掉的 lane 必须释放名额，否则队列永远差一个（= 本模块 2026-11-02 修掉的那个锁死）。
 */
// `deadline`（2026-11-03 L4 P1-3）：活着的 unconfirmed lane 越过墙钟期限后必须释放名额，
// 否则一条「进程活着但不再自报」的 lane 能把队列永久占住。
export const SLOT_FREE_STATUSES = new Set(["done", "terminal-no-result", "dead", "deadline", "skipped", "dispatch-failed"]);

/** 心跳超阈 = 死亡候选；90s = tab-runs 既定 3 个心跳周期。 */
export const HEARTBEAT_DEAD_MS = 90_000;

export interface LaneFacts {
	lane: LaneId;
	tabRunId: string;
	status: LaneFactStatus;
	/** 结果文件是否存在（terminal-no-result/dead 恒 false）。 */
	hasResult: boolean;
	/** 可读原因（判据 + 依据），写进 meta.degradedLanes。 */
	reason: string;
}

interface TabStateLite {
	terminal?: boolean;
	phase?: string;
	turn?: string;
	pid?: number;
	heartbeatAt?: string;
	lastActivityAt?: string;
}

interface TabResultLite {
	status?: string;
	autoGenerated?: boolean;
}

/**
 * 结果文件是不是 **lane 自己回报的**（`tab-finish`）。
 * `tab-runs.ts:80` 的不变量：`status==="unconfirmed" ⟺ autoGenerated===true`，
 * 两侧互相强制 ⇒ 这里同时验 status 与 autoGenerated，不依赖单侧。
 * 读不到/半截 JSON ⇒ 不算自报（保守：不释放名额，交人工/墙钟收拾）。
 */
export function isSelfReportedResult(tabRunsDir: string, tabRunId: string): boolean {
	// 2026-11-03 L4 实验验实：真实读侧 readTabResultFile 要求 id/taskId/finishedAt，且**拒绝
	// autoGenerated:false**（tab-runs.ts:453）⇒ 自报结果的真实形状是**不带该字段**。
	// 必须走**同一个校验器**，不得自己解析：否则会出现「laneFacts 认为已自报，而收集侧/事件侧
	// 因校验失败拒收同一文件」的双判据（R-2 静默失效）。
	const rec = readTabResultFile(tabRunsDir, tabRunId);
	if (!rec) return false; // 校验失败/半截/损坏 ⇒ 与收集侧同口径：拒收
	const selfStatus = rec.status === "completed" || rec.status === "failed" || rec.status === "cancelled";
	return selfStatus && rec.autoGenerated !== true;
}

const laneStateExists = (tabRunsDir: string, tabRunId: string): boolean => existsSync(tabStatePath(tabRunsDir, tabRunId));

const readTabStateLite = (tabRunsDir: string, tabRunId: string): TabStateLite | null => {
	const p = tabStatePath(tabRunsDir, tabRunId);
	if (!existsSync(p)) return null;
	try {
		const v = JSON.parse(readFileSync(p, "utf8")) as TabStateLite;
		return v && typeof v === "object" ? v : null;
	} catch {
		return null; // 半截 JSON 不判死（不误杀活 tab）
	}
};

/**
 * 逐 lane 判参与事实。never-throw。
 * `isAlive` 是 seam（测试注入）；缺省 = 真实 `process.kill(pid,0)` 探针。
 */
/**
 * 该 lane 自己的墙钟期限（2026-11-03 L4 M3）：续发 lane 在派发那一刻写 `lanes[lane].deadlineAt`；
 * 首发 lane 没有该键 ⇒ 回退 run 级 `laneDeadlineAt`（首发时它就是本 lane 的期限，正确）。
 * 缺省回退是**兼容存量 meta**，不得让「继承来的期限」判死后来起跑的 lane。
 */
function laneDeadlineMs(meta: TraceRunMeta, lane: LaneId): number | undefined {
	const own = (meta.lanes[lane] as { deadlineAt?: string } | undefined)?.deadlineAt;
	const raw = own ?? meta.laneDeadlineAt;
	if (!raw) return undefined;
	const ms = Date.parse(raw);
	return Number.isFinite(ms) ? ms : undefined;
}

export function laneFacts(
	meta: TraceRunMeta,
	tabRunsDir: string,
	opts: { now?: () => number; isAlive?: (pid: number) => boolean; queuePending?: Set<LaneId> } = {},
): LaneFacts[] {
	const now = opts.now?.() ?? Date.now();
	const isAlive = opts.isAlive ?? isProcessAlive;
	const out: LaneFacts[] = [];
	for (const lane of ["A", "B", "C"] as LaneId[]) {
		const meta2 = meta.lanes[lane];
		const status0 = meta2.laneStatus ?? "active";
		if (TERMINAL_LANE_STATUSES.has(status0)) {
			out.push({
				lane,
				tabRunId: meta2.tabRunId ?? "",
				status: status0 as "skipped" | "dispatch-failed",
				hasResult: false,
				reason: `${status0}：${meta2.laneStatusReason ?? "无原因"}`,
			});
			continue;
		}
		const id = meta2.tabRunId ?? "";
		if (!id) {
			// 无 tabRunId 只有两种台本：在队待发（排队中，不进分母）/ 派发失败空洞（一等终态）。
			// 两者都不得算「在跑」——算在跑就是本次修的缺陷：收集永远差一个。
			if (opts.queuePending?.has(lane) && !laneStateExists(tabRunsDir, id)) {
				out.push({ lane, tabRunId: "", status: "queued", hasResult: false, reason: "在 lane-queue 待发队列中（尚未派发）" });
			} else {
				out.push({ lane, tabRunId: "", status: "dispatch-failed", hasResult: false, reason: "dispatch-failed：meta 无 tabRunId 且不在待发队列" });
			}
			continue;
		}
		const hasResult = existsSync(join(tabRunsDir, `${id}.result.json`));
		const st = readTabStateLite(tabRunsDir, id);
		// 判死：只用 pid 探活 ∨ 心跳超阈（pid 缺失是实测常态，见文件头）
		const pidDead = st?.pid !== undefined && !isAlive(st.pid);
		const hbDead =
			st?.pid === undefined &&
			!!st?.heartbeatAt &&
			Number.isFinite(now - Date.parse(st.heartbeatAt)) &&
			now - Date.parse(st.heartbeatAt) > HEARTBEAT_DEAD_MS;
		if (hasResult && isSelfReportedResult(tabRunsDir, id)) {
			out.push({ lane, tabRunId: id, status: "done", hasResult: true, reason: "result.json 已存在（lane 自报终态）" });
			continue;
		}
		if (hasResult) {
			// 兜底生成的 unconfirmed 结果：tab 还活着 ⇒ **不算终态、不释放并发名额**（本次修的缺陷）。
			// 进程已死 ⇒ 终态无有效结果，释放名额（否则队列永远差一个）。
			if (pidDead || hbDead) {
				out.push({
					lane,
					tabRunId: id,
					status: "dead",
					hasResult: true,
					reason: pidDead
						? `兜底 result(unconfirmed) 且 tab 进程 pid=${st?.pid} 已不在 ⇒ 终态无有效结果`
						: `兜底 result(unconfirmed) 且 pid 缺失、心跳 ${Math.round((now - Date.parse(st!.heartbeatAt!)) / 1000)}s 前 > ${HEARTBEAT_DEAD_MS / 1000}s 阈 ⇒ 终态无有效结果`,
				});
			} else if (laneDeadlineMs(meta, lane) !== undefined && now > laneDeadlineMs(meta, lane)!) {
				// 墙钟期限到了还不自报 ⇒ **有界兜底**：释放名额并记降级（L4 P1-3：不得无限占位）。
				// 只改判定，不杀进程——杀进程是人工处置面（/trace-fusion-clean），不由本判据越权。
				out.push({
					lane,
					tabRunId: id,
					status: "deadline",
					hasResult: true,
					reason: `兜底 result(unconfirmed) 且已越过墙钟期限 ${meta.lanes[lane]?.deadlineAt ?? meta.laneDeadlineAt}（tab 进程仍存活）⇒ 释放并发名额并记降级；lane 进程未由本判据终止，人工处置用 /trace-fusion-clean`,
				});
			} else {
				out.push({
					lane,
					tabRunId: id,
					status: "unconfirmed",
					hasResult: true,
					reason: `兜底 result(unconfirmed, autoGenerated) 且 tab 仍在跑 ⇒ 不算终态、不释放并发名额（中止/回合结束不得连锁起下一条）`,
				});
			}
			continue;
		}
		if (st?.terminal === true) {
			out.push({ lane, tabRunId: id, status: "terminal-no-result", hasResult: false, reason: `tab 已终态（phase=${st.phase ?? "?"}）但无 result.json` });
			continue;
		}
		if (pidDead) {
			out.push({ lane, tabRunId: id, status: "dead", hasResult: false, reason: `tab 进程 pid=${st?.pid} 已不在` });
			continue;
		}
		if (hbDead) {
			out.push({
				lane,
				tabRunId: id,
				status: "dead",
				hasResult: false,
				reason: `pid 缺失且心跳 ${Math.round((now - Date.parse(st!.heartbeatAt!)) / 1000)}s 前 > ${HEARTBEAT_DEAD_MS / 1000}s 阈`,
			});
			continue;
		}
		// 没有任何 state 文件（派发后 wt 未起到写 state 就挂了）⇒ 无从判活，保守算在跑；
		// 这类 lane 由墙钟时限 / 人工 /trace-fusion-clean 收拾，**不得被当作全部终态而提前收集**。
		out.push({ lane, tabRunId: id, status: "running", hasResult: false, reason: st ? `在跑（phase=${st.phase ?? "?"}）` : "在跑（无 state 文件，无从判活 ⇒ 保守等待）" });
	}
	return out;
}

/**
 * 不可用 lane（降级项）。`unconfirmed` 不算降级：那是**还在跑的活 lane**，
 * 只是回合结束时没自报结果；把它当降级会让 Hard Facts 谎报「该 lane 不可用」。
 */
export const degradedFacts = (facts: LaneFacts[]): LaneFacts[] =>
	facts.filter((f) => f.status !== "done" && f.status !== "running" && f.status !== "queued" && f.status !== "unconfirmed");

/**
 * 把降级原因写进 meta（`degradedLanes`）。原子重写 meta；写失败 ⇒ 返回 false（调用方记日志，不静默）。
 */
export function writeDegradedLanes(meta: TraceRunMeta, facts: LaneFacts[], now?: () => number): boolean {
	const degraded = degradedFacts(facts).map((f) => ({ lane: f.lane, tabRunId: f.tabRunId, status: f.status, reason: f.reason }));
	try {
		const path = metaPath(meta.runDir);
		const raw = existsSync(path) ? (JSON.parse(readFileSync(path, "utf8")) as Record<string, unknown>) : {};
		writeFileSync(path, JSON.stringify({ ...raw, degradedLanes: degraded, degradedAt: new Date(now?.() ?? Date.now()).toISOString() }, null, 2) + "\n", "utf8");
		return true;
	} catch {
		return false;
	}
}
