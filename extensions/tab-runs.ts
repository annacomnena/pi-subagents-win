/** 列出全部派发记录（按 dispatchedAt 倒序，支持 limit）。 */
export function listTabDispatches(runsDir: string, limit = 100): TabDispatchRecord[] {
	if (!existsSync(runsDir)) return [];
	const out: TabDispatchRecord[] = [];
	for (const f of readdirSync(runsDir)) {
		if (!f.endsWith(".json") || f.endsWith(".state.json") || f.endsWith(".result.json") || f.endsWith(".tmp")) continue;
		const r = readTabDispatch(runsDir, f.slice(0, -".json".length));
		if (r) out.push(r);
	}
	out.sort((a, b) => Date.parse(b.dispatchedAt) - Date.parse(a.dispatchedAt));
	return limit > 0 ? out.slice(0, limit) : out;
}

/**
 * 自动归档已完成/失败且超龄的 tab-runs 文件到 _archived 目录，防止活跃目录文件无限积压导致内存和 I/O 爆炸。
 * @param runsDir tab-runs 根目录
 * @param maxAgeHours 超过多少小时的已终态跑次移入 _archived（默认 72 小时 / 3 天）
 * @returns 成功归档的 runId 数量
 */
export function archiveStaleTabRuns(runsDir: string, maxAgeHours = 72): number {
	if (!existsSync(runsDir)) return 0;
	const archiveDir = join(runsDir, "_archived");
	const cutoffMs = Date.now() - maxAgeHours * 3600 * 1000;
	let archivedCount = 0;

	try {
		const files = readdirSync(runsDir);
		const runIds = new Set<string>();
		for (const f of files) {
			if (f.endsWith(".json") && !f.endsWith(".state.json") && !f.endsWith(".result.json") && !f.endsWith(".tmp")) {
				runIds.add(f.slice(0, -".json".length));
			}
		}

		for (const id of runIds) {
			const dispatchPath = join(runsDir, `${id}.json`);
			const resultPath = join(runsDir, `${id}.result.json`);
			const statePath = join(runsDir, `${id}.state.json`);
			const notifiedPath = join(runsDir, `${id}.notified`);

			// 防护：若任务处于**非终态**活跃状态，绝不归档。
			//
			// 2026-10-16 修根因：旧实现只挡 working/attached，遗漏了 **waiting** ——
			// 那是**活着的空闲 tab**（在等输入/等下次唤醒），被归档后其派发账本被移走 ⇒
			// `steer` 只查活跃目录 ⇒ 报 `unknown tab` 并**静默丢消息**（实测事故）。
			//
			// 语义：**“非终态”就不归档**，终态的证据有三条任一即可（不要求单一字段）：
			//   ① state.phase 属终态集合；② state.terminal === true；③ 存在 result 文件。
			// 三者全无 ⇒ 保守不归档（宁可积压也不丢消息；无 state 不代表已终态）。
			//
			// RF-1（2026-10-18）：证据③收窄 —— **兜底 unconfirmed 结果不算终态证据**
			//（composeTabStatus 对它判 terminal=false；steer:97 / timers:179 已同口径 isUnconfirmedFallback）。
			// 否则「沉默但活着」的 tab 超龄后被移出活跃目录 ⇒ listTabDispatches / frontier / supervision
			// 全部丢失载体，RF-1 的「可感知」恰在长程沉默场景下失效；且违背本段自己声明的
			//「『非终态』就不归档」语义。真三态结果 / 损坏文件维持旧行为（文件存在即证据）。
			let terminalEvidence = existsSync(resultPath) && !isUnconfirmedFallback(readTabResultFile(runsDir, id));
			if (existsSync(statePath)) {
				try {
					const s = JSON.parse(readFileSync(statePath, "utf8")) as { phase?: string; terminal?: boolean } | null;
					const TERMINAL_PHASES = ["completed", "failed", "cancelled", "orphaned"];
					if (s && (TERMINAL_PHASES.includes(String(s.phase)) || s.terminal === true)) terminalEvidence = true;
				} catch { /* 半截/损坏 state：不据此判定（下方 terminalEvidence 仍可能来自 result） */ }
			}
			if (!terminalEvidence) continue;

			// 传 maxAgeHours === 0 时：仅归档已具备终态的跑次
			if (maxAgeHours === 0) {
				const hasResult = existsSync(resultPath);
				let isTerminalState = false;
				if (existsSync(statePath)) {
					try {
						const s = JSON.parse(readFileSync(statePath, "utf8"));
						if (s && ["completed", "failed", "cancelled", "orphaned"].includes(s.phase)) {
							isTerminalState = true;
						}
					} catch { /* ignore */ }
				}
				const isFailedDispatch = dispatch?.dispatchStatus === "launch_failed";
				if (!hasResult && !isTerminalState && !isFailedDispatch) {
					continue;
				}
			}

			// 判断是否超龄：优先读取 dispatch 的 dispatchedAt，其次 raw JSON，再次 stat.mtimeMs
			let targetTime = 0;
			const dispatch = readTabDispatch(runsDir, id);
			if (dispatch?.dispatchedAt) {
				const parsed = Date.parse(dispatch.dispatchedAt);
				if (!Number.isNaN(parsed)) targetTime = parsed;
			}
			if (targetTime === 0 && existsSync(dispatchPath)) {
				try {
					const raw = JSON.parse(readFileSync(dispatchPath, "utf8"));
					if (raw?.dispatchedAt) {
						const parsed = Date.parse(raw.dispatchedAt);
						if (!Number.isNaN(parsed)) targetTime = parsed;
					}
				} catch { /* ignore */ }
			}
			if (targetTime === 0) {
				try {
					if (existsSync(resultPath)) {
						targetTime = statSync(resultPath).mtimeMs;
					} else if (existsSync(dispatchPath)) {
						targetTime = statSync(dispatchPath).mtimeMs;
					}
				} catch {
					continue;
				}
			}

			if (targetTime > 0 && targetTime < cutoffMs) {
				if (!existsSync(archiveDir)) mkdirSync(archiveDir, { recursive: true });
				const related = [dispatchPath, resultPath, statePath, notifiedPath];
				for (const p of related) {
					if (existsSync(p)) {
						const dest = join(archiveDir, basename(p));
						try {
							if (existsSync(dest)) unlinkSync(dest);
							renameSync(p, dest);
						} catch {
							/* ignore individual file move error */
						}
					}
				}
				archivedCount++;
			}
		}
	} catch {
		/* ignore errors */
	}
	return archivedCount;
}

/** 校验 TabState（宽松校验）。 */
export function validateTabState(raw: unknown): { ok: boolean; errors: string[]; value?: TabState } {
	const record = asRecord(raw);
	if (!record) return { ok: false, errors: ["not an object"] };
	const errors: string[] = [];
	const str = (v: unknown): string | undefined => (typeof v === "string" ? v : undefined);
	if (!str(record.id)) errors.push("id required");
	const phase = str(record.phase);
	if (!phase || !["attached", "working", "waiting", "completed", "failed", "cancelled", "orphaned"].includes(phase)) {
		errors.push(`phase invalid: ${String(phase)}`);
	}
	const turn = str(record.turn);
	if (turn && !["working", "idle", "error", "unknown"].includes(turn)) errors.push(`turn invalid: ${String(turn)}`);
	if (typeof record.terminal !== "boolean") errors.push("terminal must be boolean");
	if (errors.length > 0) return { ok: false, errors };
	const value: TabState = {
		id: str(record.id)!,
		phase: (phase as TabState["phase"]) ?? "attached",
		turn: (turn as TabState["turn"]) ?? "unknown",
		terminal: record.terminal as boolean,
	};
	const sessionPath = str(record.sessionPath);
	if (sessionPath !== undefined) value.sessionPath = sessionPath;
	if (typeof record.pid === "number") value.pid = record.pid;
	const lastActivityAt = str(record.lastActivityAt);
	if (lastActivityAt !== undefined) value.lastActivityAt = lastActivityAt;
	const currentToolStartedAt = str(record.currentToolStartedAt);
	if (currentToolStartedAt !== undefined) value.currentToolStartedAt = currentToolStartedAt;
	const lastAssistantText = str(record.lastAssistantText);
	if (lastAssistantText !== undefined) value.lastAssistantText = lastAssistantText;
	const lastStopReason = str(record.lastStopReason);
	if (lastStopReason !== undefined) value.lastStopReason = lastStopReason;
	const err = str(record.error);
	if (err !== undefined) value.error = err;
	if (asRecord(record.usage)) {
		const u = asRecord(record.usage)!;
		const n = (v: unknown): number => (typeof v === "number" && Number.isFinite(v) ? v : 0);
		value.usage = {
			input: n(u.input), output: n(u.output), cacheRead: n(u.cacheRead),
			cacheWrite: n(u.cacheWrite), cost: n(u.cost), turns: n(u.turns),
		};
	}
	return { ok: true, errors, value };
}

