/**
 * tab-runs — 标签页回收（reclaim）核心纯函数模块
 *
 * 目标：让主会话能对 launch-tabs 派发的标签页做「回收」——
 * 派发时落账本（tab-runs/<runId>.json）、轮询 session JSONL 探活、
 * 读取结构化结果文件，支撑超长程任务的编排与推进。
 *
 * 本模块只含纯函数与最小文件 IO，不注册任何工具、不修改 launch 流程
 * （阶段 0：先证明「按 taskId 前缀命中 session + 保守判态」成立）。
 *
 * 状态语义（保守原则，来自 GPT/GLM 研究报告共识）：
 *   - 只有显式结果文件（result.json）才能给出工作流终态 completed/failed/cancelled。
 *   - session JSONL 的 stopReason 只是「单轮消息原因」：
 *       toolUse → 仍在工作；stop/length → 等待输入（waiting，不是完成）；
 *       error/aborted → 本回合失败（unconfirmed，非工作流终态）。
 *   - 缺失显式结果时一律标 unconfirmed/resultMissing，绝不静默当完成。
 */

import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, statSync, unlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { basename, dirname, join } from "node:path";
import { modePrefix, type LaunchMode } from "./launch.ts";

// ── 类型 ───────────────────────────────────────────────────────────

/** tab 模式：workflow 四模式 + trace-fusion 的 trace worker（不进 launch.ts 的 prompt 前缀体系）。 */
export type TabMode = LaunchMode | "trace";

/** 派发时主会话写入的账本记录（launch-tabs 每 task 一条）。 */
export interface TabDispatchRecord {
	/** runId，回收闭环的唯一令牌。 */
	id: string;
	version: 1;
	taskId: string;
	mode: TabMode;
	title?: string;
	/** 解析后的绝对 cwd（决定 session 桶）。 */
	cwd: string;
	requestedModel?: string;
	dispatchedAt: string;
	dispatchStatus: "dispatched" | "launch_failed";
	error?: string;
	/** 直开（/launch）标签页：无任务号、用户自定任务（身份仍需要 runId）。 */
	direct?: boolean;
}

export interface TabUsage {
	input: number;
	output: number;
	cacheRead: number;
	cacheWrite: number;
	cost: number;
	turns: number;
}

/**
 * 结果状态四态（2026-10-18 RF-1）：
 *   completed|failed|cancelled —— tab 自己调用 tab-finish 声明的**工作流终态**；
 *   unconfirmed              —— **兜底生成**（tab 回合结束但没调 tab-finish），非 tab 自报，
 *                               不是工作流终态（terminal=false），要求主会话核实。
 * 为什么要第四态：兜底若落三态值，等于把「没回报」伪装成「完成」（违反 RF-1 硬约束 1）。
 */
export type TabResultStatus = "completed" | "failed" | "cancelled" | "unconfirmed";

/** 标签页工作流终态结果（由 tab-finish 工具 / 兜底写入器写入）。 */
export interface TabResult {
	id: string;
	taskId: string;
	status: TabResultStatus;
	finishedAt: string;
	summary?: string;
	finalText?: string;
	artifacts?: string[];
	reportPath?: string;
	openIssues?: string[];
	usage?: TabUsage;
	/**
	 * true = **兜底生成**（`writeSettlementFallback` 写的），不是 tab 自报。
	 * 缺失 = tab 自报（v1 不引入第二个 falsy 形状，与 `supervision.ts::validateEntry` 的 optOut 同口径）。
	 * 不变量：`status === "unconfirmed"` ⟺ `autoGenerated === true`（两侧互相强制）。
	 */
	autoGenerated?: boolean;
}

/** 单个 session JSONL 文件的探测结果。 */
export interface SessionProbe {
	filePath: string;
	/** 首条 user 消息文本是否以「根据<mode>进行工作<taskId>」前缀命中。 */
	matched: boolean;
	matchReason?: string;
	sessionId?: string;
	sessionCwd?: string;
	sessionTimestamp?: string;
	lastRole?: "user" | "assistant" | "toolResult" | "unknown";
	lastStopReason?: string;
	lastAssistantText?: string;
	usage?: TabUsage;
	messageCount: number;
	/** 探测到的首条 user 文本（截断，供诊断）。 */
	firstUserTextPreview?: string;
}

/** 保守判态结果。 */
export interface TabStatus {
	/** 生命周期阶段：只有 completed/failed/cancelled 是工作流终态。 */
	phase:
		| "dispatched"
		| "attached"
		| "working"
		| "waiting"
		| "completed"
		| "failed"
		| "cancelled"
		| "orphaned"
		| "unconfirmed";
	/** 当前回合：working / idle / error / unknown。 */
	turn: "working" | "idle" | "error" | "unknown";
	terminal: boolean;
	resultMissing: boolean;
	lastStopReason?: string;
	lastAssistantText?: string;
	usage?: TabUsage;
	source: "ledger-only" | "session-jsonl" | "result-file";
	note?: string;
}

/** 生命周期阶段联合（TabStatusView.phase 的权威定义；原先这个类型名被引用但未定义）。 */
export type TabLifecyclePhase = TabStatus["phase"];

